function storyOrder(): Task {
  const s = pick(stories);
  return {
    kind: 'order',
    topic: 'storyorder',
    prompt: 'Әңгімені оқы да, оқиғаларды ретімен қой.',
    visual: { type: 'text', value: s.text },
    items: s.events.map((e, i) => ({ id: `${i}-${e}`, label: e })),
    hints: ['Әңгіменің басы мен соңын тап.', `Бірінші оқиға: «${s.events[0]}».`, s.events.join(' → ')],
  };
}

function storyQuestion(): Task {
  const s = pick(stories);
  const q = pick(s.qs);
  return {
    kind: 'choice',
    topic: 'storyq',
    prompt: q.q,
    visual: { type: 'text', value: s.text },
    layout: 'list',
    options: textOptions(q.a, q.w),
    answer: q.a,
    hints: ['Мәтінді тағы бір рет оқы немесе тыңда.', 'Кейіпкердің не істегеніне назар аудар.', `Жауабы: ${q.a}.`],
  };
}

