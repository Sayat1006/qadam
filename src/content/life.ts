function shopping(level: number): () => Task {
  return () => {
    const items = [
      { w: 'нан', e: '🍞', p: [150, 200, 250] },
      { w: 'сүт', e: '🥛', p: [350, 400, 450] },
      { w: 'жұмыртқа', e: '🥚', p: [100, 150] },
      { w: 'алма', e: '🍎', p: [100, 120, 150] },
      { w: 'дәптер', e: '📒', p: [80, 100, 150] },
    ];
    const a = pick(items);
    const b = pick(items.filter((x) => x !== a));
    const pa = pick(a.p);
    const pb = pick(b.p);
    if (level <= 3) {
      return {
        kind: 'numpad',
        topic: 'shopping',
        prompt: `${a.e} ${a.w} — ${pa} ₸, ${b.e} ${b.w} — ${pb} ₸. Екеуі бірге қанша тұрады?`,
        answer: pa + pb,
        unit: '₸',
        hints: ['Екі бағаны қосу керек.', `${pa} + ${pb} = ? Алдымен жүздіктерді қос.`, `${pa} + ${pb} = ${pa + pb} теңге.`],
      };
    }
    const n = rand(2, 3);
    const total = pa * n + pb;
    const m = total <= 500 ? 500 : total <= 1000 ? 1000 : 2000;
    return {
      kind: 'numpad',
      topic: 'shopping',
      prompt: `Сен ${n} ${a.w} (біреуі ${pa} ₸) және 1 ${b.w} (${pb} ₸) алдың. Сатушыға ${m} ₸ бердің. Қайтарым қанша?`,
      answer: m - total,
      unit: '₸',
      hints: [
        'Алдымен барлық сатып алғаныңның бағасын есепте, сосын ақшадан шегер.',
        `Барлығы: ${n} × ${pa} + ${pb} = ${total} ₸.`,
        `${m} − ${total} = ${m - total} ₸.`,
      ],
    };
  };
}

