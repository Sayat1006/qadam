import { describe, expect, it } from 'vitest';
import { plural } from '../../content/kazakh';

describe('көптік жалғау', () => {
  it.each([
    ['ит', 'иттер'], ['алма', 'алмалар'], ['мысық', 'мысықтар'], ['үй', 'үйлер'], ['гүл', 'гүлдер'],
    ['қоян', 'қояндар'], ['аю', 'аюлар'], ['жұлдыз', 'жұлдыздар'], ['көлік', 'көліктер'], ['түйе', 'түйелер'],
    ['қой', 'қойлар'], ['сиыр', 'сиырлар'], ['піл', 'пілдер'], ['әтеш', 'әтештер'], ['сәбіз', 'сәбіздер'],
  ])('%s → %s', (w, p) => expect(plural(w)).toBe(p));
});
