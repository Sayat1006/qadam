import { describe, expect, it } from 'vitest';
import { isLatin, kkNumber, normalizeKk } from '../kkspeech';

describe('kkNumber', () => {
  it.each([
    [0, 'нөл'],
    [1, 'бір'],
    [11, 'он бір'],
    [45, 'қырық бес'],
    [100, 'жүз'],
    [250, 'екі жүз елу'],
    [1000, 'мың'],
    [1350, 'мың үш жүз елу'],
    [21000, 'жиырма бір мың'],
  ])('%i → %s', (n, w) => expect(kkNumber(n)).toBe(w));
});

describe('normalizeKk', () => {
  it.each([
    ['3 + 2 = ?', 'үш қосу екі тең неше'],
    ['7 + ? = 18', 'жеті қосу неше тең он сегіз'],
    ['6 × 7 = ?', 'алты көбейту жеті тең неше'],
    ['12 : 3 = ?', 'он екі бөлу үш тең неше'],
    ['Сағат 9:15-де басталады', 'Сағат тоғыз он бесте басталады'],
    ['5-ке дейін', 'беске дейін'],
    ['10-нан кейін', 'оннан кейін'],
    ['3/4', 'төрттен үш'],
    ['250 ₸', 'екі жүз елу теңге'],
    ['5-деңгей', 'бес деңгей'],
    ['14 > 9', 'он төрт үлкен тоғыз'],
  ])('%s', (a, b) => expect(normalizeKk(a)).toBe(b));

  it('эмодзиді алып тастайды', () => expect(normalizeKk('🍎 алма')).toBe('алма'));
});

describe('isLatin', () => {
  it('ағылшын мәтінін таниды', () => {
    expect(isLatin('Hello')).toBe(true);
    expect(isLatin('Сәлем')).toBe(false);
  });
});
